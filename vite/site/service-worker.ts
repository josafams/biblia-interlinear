// sw.js: keeps the site for offline use. Everything is precached except chapters, concordance,
// search and videos (they are cached when read). The cache name is a hash of the whole output,
// so any change to the site installs a new worker. Written last, after every other file.
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { OUT } from "./app";

const LAZY = ["dados/cap/", "dados/conc/", "dados/busca/", "videos/"];

function listFiles(dir: string, base = ""): string[] {
  return fs.readdirSync(dir).flatMap(f => {
    const full = path.join(dir, f),
      rel = base ? `${base}/${f}` : f;
    return fs.statSync(full).isDirectory() ? listFiles(full, rel) : [rel];
  });
}

export function writeServiceWorker() {
  const files = listFiles(OUT).sort();
  const hash = crypto.createHash("sha256");
  for (const f of files) hash.update(f).update(fs.readFileSync(path.join(OUT, f)));
  const version = hash.digest("hex").slice(0, 12);
  const precache = ["./", ...files.filter(f => !f.endsWith(".txt") && !LAZY.some(p => f.startsWith(p)))];
  fs.writeFileSync(path.join(OUT, "sw.js"), workerSource(version, precache));
  return { files: files.length + 1, version };
}

const workerSource = (version: string, precache: string[]) => `// Generated by vite/site/service-worker.ts — do not edit
const CACHE = "interlinear-${version}";
const FILES = ${JSON.stringify(precache)};
self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin) return;
  // "Como usar" videos are re-recorded apart from the site: the index always comes from the network (with a copy
  // for offline use) and the video files skip the cache (they are large and arrive in ranges).
  if (url.pathname.includes("/videos/")) {
    if (!url.pathname.endsWith("/videos.js")) return;
    e.respondWith(fetch(e.request, { cache: "no-cache" }).then(r => {
      if (r.ok) {
        const copy = r.clone();
        caches.open(CACHE).then(c => c.put(e.request, copy));
      }
      return r;
    }).catch(() => caches.match(e.request, { ignoreSearch: true })));
    return;
  }
  // Pages (index.html, ler.html…): from the network when online, so an old version never shows; the cache is
  // for offline use
  if (e.request.mode === "navigate") {
    e.respondWith(fetch(e.request, { cache: "no-cache" }).then(r => {
      if (r.ok) {
        const copy = r.clone();
        caches.open(CACHE).then(c => c.put(e.request, copy));
      }
      return r;
    }).catch(() => caches.match(e.request, { ignoreSearch: true }).then(hit => hit || caches.match("./"))));
    return;
  }
  e.respondWith(caches.open(CACHE).then(c => c.match(e.request, { ignoreSearch: true }).then(hit => hit || fetch(e.request).then(r => {
    if (r.ok) c.put(e.request, r.clone());
    return r;
  }))));
});
`;
